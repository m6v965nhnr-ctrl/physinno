export default function CasePresentationHowTo() {
  return (
    <div className="column-body">
      <p>
        院内の症例検討会や学会での症例発表は、経験年数に関わらず「何を、どの順番で、どこまで書けばいいのか」で悩む人が多いテーマです。この記事では、症例報告・症例発表の基本的な構成と、伝わる考察の書き方、そして評価者からよく指摘される減点ポイントを整理しました。
      </p>

      <h2>症例報告の基本構成</h2>
      <p>
        形式は施設や学会によって多少異なりますが、多くの症例報告は次の流れで構成されています。まずはこの型を押さえることが、読みやすい症例報告への一番の近道です。
      </p>
      <ol>
        <li>
          <strong>はじめに（背景）</strong>
          ：対象疾患や介入の一般的な背景、この症例を報告する意義を簡潔に述べる
        </li>
        <li>
          <strong>症例紹介</strong>
          ：年齢・性別・診断名・現病歴・既往歴・社会的背景（匿名化した範囲で）
        </li>
        <li>
          <strong>評価</strong>
          ：初期評価の結果（身体機能・ADL・画像所見など、目的に応じた項目）
        </li>
        <li>
          <strong>介入（治療プログラム）</strong>
          ：実施した理学療法の内容と、期間・頻度・段階的な変更点
        </li>
        <li>
          <strong>結果</strong>
          ：再評価の結果。初期評価と対応する形で数値・所見を示すと変化が伝わりやすい
        </li>
        <li>
          <strong>考察</strong>
          ：結果の解釈、先行研究や理論との整合性、介入がうまくいった（あるいはいかなかった）理由
        </li>
        <li>
          <strong>まとめ</strong>
          ：この症例から得られた示唆、今後の課題
        </li>
      </ol>

      <h2>考察で差がつく3つのポイント</h2>
      <p>
        症例報告の評価は「結果」より「考察」で決まると言われます。同じ結果でも、考察の書き方次第で説得力が大きく変わります。
      </p>
      <h3>1. 結果を並べるだけで終わらせない</h3>
      <p>
        「〇〇が改善した」で終わらず、「なぜ改善したと考えられるか」を、介入内容・評価結果・先行知見の3つを結びつけて説明します。改善しなかった項目がある場合も、その理由に触れると考察の厚みが増します。
      </p>
      <h3>2. 他の可能性にも触れる</h3>
      <p>
        改善の要因を介入だけに帰結させず、自然経過や他職種の関わり、環境要因など、他に考えられる要因にも言及すると、客観性のある考察として評価されやすくなります。
      </p>
      <h3>3. 限界（リミテーション）を書く</h3>
      <p>
        単一症例である以上、一般化には限界があります。「この結果がすべての同様の症例に当てはまるわけではない」という視点を一文でも入れておくと、質の高い報告として受け取られます。
      </p>

      <h2>よくある減点ポイント</h2>
      <ul>
        <li>評価項目が初期評価と再評価で揃っていない（比較できない）</li>
        <li>介入内容が「〇〇療法を実施した」で終わり、頻度・量・段階付けの記載がない</li>
        <li>個人が特定できる情報（詳細な年齢・実名に近い記載・施設名など）が残っている</li>
        <li>考察が結果の言い換えになっている（新しい視点が加わっていない）</li>
        <li>参考文献が本文の主張と対応していない</li>
      </ul>

      <div className="column-note">
        Re:lightでは症例報告に疾患カテゴリ・参考URLを添えて投稿でき、他のPTからコメントで意見をもらえます。院内発表の前に一度アウトプットして反応を見る、という使い方もおすすめです。
      </div>

      <h2>まとめ</h2>
      <p>
        症例報告は「型」を押さえるだけで一気に書きやすくなります。まずは基本構成に沿って書き出し、考察部分で「なぜそうなったか」「他の可能性はないか」「この症例だけで言えることの限界は何か」の3点を意識してみてください。
      </p>
    </div>
  );
}
