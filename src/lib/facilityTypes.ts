export function typesOf(category: string): string[] {
  return FACILITY_CATEGORIES.find((c) => c.category === category)?.types ?? [];
}

// 保存してよい値か（画面からの入力を、決まった一覧に限る）
export function isValidFacility(category: string, type: string | null | undefined): boolean {
  const c = FACILITY_CATEGORIES.find((x) => x.category === category);
  return !!c && (!type || c.types.includes(type));
}
